#!/usr/bin/env python3
"""The proof of how far a session got, from its own log: every change of the game's stage byte
([A923]+0x3C) and season word (+0x38), and every full-time board of a match of TEAM, with the step,
the host time and the fixture index. Reads out/<S>/steps.jsonl and screens.jsonl; no game is run.

    python3 experiments/E031-play-the-game/progress.py S [--team Holland] [--md out/S/progress.md]

A board is a screen that shows "---- FULL TIME ----" in the commentary rows and the two team names
in rows 1 and 3 (the scoreboard); a board seen several times is one match (keyed by fixture index
and teams). Each line names the step whose screen holds it, so `screen.py S STEP` shows it whole."""
import argparse
import json
import re
from pathlib import Path

OUT = Path(__file__).resolve().parent / "out"


def board(text, team):
    rows = text.split("\n")
    if len(rows) < 5 or "FULL TIME" not in "".join(r[32:67] for r in rows[1:4]):
        return None
    m1 = re.search(r"│([A-Z][A-Z .']+?)-*│\s*(\d+)│", rows[1])
    m3 = re.search(r"│([A-Z][A-Z .']+?)-*│\s*(\d+)│", rows[3])
    if not (m1 and m3) or team.upper() not in (m1.group(1).strip(), m3.group(1).strip()):
        return None
    kind = re.search(r"┬([A-Z0-9][A-Z0-9 .-]*?)─", rows[0])
    return (m1.group(1).strip(), int(m1.group(2)), m3.group(1).strip(), int(m3.group(2)),
            kind.group(1) if kind else "")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("session")
    ap.add_argument("--team", default="Holland")
    ap.add_argument("--md")
    a = ap.parse_args()
    d = OUT / a.session
    screens = {}
    for line in (d / "screens.jsonl").read_text().splitlines():
        s = json.loads(line)
        screens[s["digest"]] = s["text"]
    lines, seen, last = [], set(), None
    for line in (d / "steps.jsonl").read_text().splitlines():
        st = json.loads(line)
        info = st.get("info") or {}
        req = st.get("req") or {}
        if req.get("cmd") in ("launch", "terminated"):
            what = f"launch (saved games copied in: {', '.join(req.get('gl') or []) or 'none'})" \
                if req["cmd"] == "launch" else "server stopped, emulator terminated"
            lines.append(f"| {st['n']} | {st['utc'][:19]} | {what} | |")
            last = None
        if info and info.get("stage") is not None:
            key = (info.get("season"), info.get("stage"))
            if key != last:
                lines.append(f"| {st['n']} | {st['utc'][:19]} | stage {info.get('stage')}, season word {info.get('season')}, "
                             f"fixture {info.get('fixture')}/{info.get('fixtures')} | |")
                last = key
        b = board(screens.get(st.get("digest"), ""), a.team)
        if b:
            k = (info.get("fixture"), b[0], b[2])
            if k not in seen:
                seen.add(k)
                lines.append(f"| {st['n']} | {st['utc'][:19]} | {b[4].lower()} | {b[0]} {b[1]}-{b[3]} {b[2]} |")
    head = f"# {a.session}: progress\n\nGenerated by `progress.py {a.session}` from the session's log.\n\n" \
           "| step | host UTC | event | match |\n| --- | --- | --- | --- |\n"
    text = head + "\n".join(lines) + "\n"
    if a.md:
        Path(a.md).write_text(text)
    print(text)


if __name__ == "__main__":
    main()
