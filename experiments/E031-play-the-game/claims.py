#!/usr/bin/env python3
"""Check every observed claim of the guide against the session logs and write out/claims.md.

claims.tsv: id, claim, kind, session, step, needle.
- kind `screen`: the needle is in the logged screen after the step (the first such step when the
  step is empty);
- kind `log`: the needle is in the step's own log line (the request, its result, an error);
- kind `file`: the needle names a tracked file that holds the evidence;
- kind `anyscreen`: the needle is in a logged screen that has no step of its own (a card `scan` read).
Exit 1 when a claim's needle is not where it says. No game is run.
Usage: python3 experiments/E031-play-the-game/claims.py [--md out/claims.md]"""
import argparse
import csv
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"


def session(name, cache={}):
    if name not in cache:
        d = OUT / name
        screens = {}
        for line in (d / "screens.jsonl").read_text().splitlines():
            s = json.loads(line)
            screens[s["digest"]] = s["text"]
        steps = [(json.loads(line), line) for line in (d / "steps.jsonl").read_text().splitlines()]
        cache[name] = (steps, screens)
    return cache[name]


def resolve(row):
    if row["kind"] == "file":
        p = HERE / row["needle"]
        return (row["needle"], "") if p.exists() else (None, "")
    steps, screens = session(row["session"])
    if row["kind"] == "anyscreen":  # a screen logged without a step of its own (the cards a scan read)
        for digest, text in screens.items():
            if row["needle"] in text:
                line = next(r for r in text.split("\n") if row["needle"] in r)
                return f"{row['session']} screens.jsonl, digest {digest[:12]}", line.strip()
        return None, ""
    want = int(row["step"]) if row["step"] else None
    for st, raw in steps:
        if want is not None and st["n"] != want:
            continue
        hay = raw if row["kind"] == "log" else screens.get(st.get("digest"), "")
        if row["needle"] in hay:
            line = next((r for r in hay.split("\n") if row["needle"] in r), "") if row["kind"] == "screen" else ""
            return f"{row['session']} step {st['n']} ({st['utc'][11:19]} UTC)", line.strip()
    return None, ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--md", default=str(OUT / "claims.md"))
    a = ap.parse_args()
    rows = list(csv.DictReader((HERE / "claims.tsv").open(), delimiter="\t", quoting=csv.QUOTE_NONE))
    out = ["# The guide's observed claims and the logged steps that show them", "",
           "Generated by `claims.py` from `claims.tsv` and the session logs; `screen.py <session> <step>` "
           "prints the whole screen. A claim the guide marks *F030*, *manual*, *listing* or *not seen* is "
           "not in this table.", "", "| id | claim | evidence | the row that holds it |", "| --- | --- | --- | --- |"]
    bad = 0
    for r in rows:
        where, line = resolve(r)
        if where is None:
            bad += 1
            print(f"NOT FOUND {r['id']}: {r['needle']!r} in {r['session']} {r['step']}")
            where = "**not found**"
        cell = line.replace("|", "│")[:90]
        out.append(f"| {r['id']} | {r['claim']} | {where} | `{cell}` |" if cell else f"| {r['id']} | {r['claim']} | {where} | |")
    Path(a.md).write_text("\n".join(out) + "\n")
    # every [Cnn] tag of the guide names a row here
    import re
    guide = (HERE.parents[1] / "docs" / "play-guide.md").read_text()
    ids = {r["id"] for r in rows}
    tags = set()
    for group in re.findall(r"\[(C\d+[a-z]?(?:, C\d+[a-z]?)*)\]", guide):
        tags.update(t.strip() for t in group.split(","))
    for t in sorted(tags - ids):
        bad += 1
        print(f"the guide cites {t}, which claims.tsv does not have")
    print(f"the guide cites {len(tags)} claims")
    print(f"{len(rows) - bad} of {len(rows)} claims found where claims.tsv says")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
