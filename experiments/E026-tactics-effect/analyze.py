#!/usr/bin/env python3
"""E026: summarise the arm logs (out/<arm>-s*.jsonl) into a markdown table.

    python3 -B experiments/E026-tactics-effect/analyze.py out-file.md

Per arm and per measure (side 0 = the team whose tactic byte was changed, Denmark; side 1 = the
opponent): N, mean, and for every non-base arm the difference to the base arm with a 95% interval,
twice: unpaired (Welch, 1.96 standard errors; the intervals are large-sample normal, N is 30-90)
and paired by seed (the same seed in both arms: match i of an arm and of the base share DS:7B62 at
the kick-off; they diverge as soon as the tactic is read, so pairing buys little and is reported
beside the unpaired figure). Runs that did not reach the board are listed and left out. Refuses to
overwrite its output."""
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ARMS = ["base"] + [f"e{k}" for k in range(1, 9)]
MEASURES = [
    ("goals for", lambda r: r["score"][0]),
    ("goals against", lambda r: r["score"][1]),
    ("goal difference", lambda r: r["score"][0] - r["score"][1]),
    ("shots for", lambda r: r["stats"]["Shots"][0]),
    ("shots against", lambda r: r["stats"]["Shots"][1]),
    ("on target for", lambda r: r["stats"]["On target"][0]),
    ("corners for", lambda r: r["stats"]["Corners"][0]),
    ("free kicks for", lambda r: r["stats"]["Free kicks"][0]),
    ("fouls by us", lambda r: r["stats"]["Fouls"][0]),
    ("fouls by them", lambda r: r["stats"]["Fouls"][1]),
    ("bookings us", lambda r: r["stats"]["Bookings"][0]),
    ("bookings them", lambda r: r["stats"]["Bookings"][1]),
    ("red cards us", lambda r: r["stats"]["Red cards"][0]),
    ("possession counter (us share %)", lambda r: 100.0 * r["stats"]["Possession"][0] / max(1, sum(r["stats"]["Possession"]))),
    ("territory counter (us share %)", lambda r: 100.0 * r["stats"]["Territory"][0] / max(1, sum(r["stats"]["Territory"]))),
]


def load():
    runs = {a: {} for a in ARMS}
    bad = []
    for f in sorted(HERE.glob("out/*-s*.jsonl")):
        for line in f.read_text().splitlines():
            r = json.loads(line)
            if r.get("error") or not r.get("stopped_at_board") or r.get("strays"):
                bad.append((f.name, r["arm"], r["seed"], r.get("error")))
                continue
            runs[r["arm"]][r["seed"]] = r
    return runs, bad


def mean_sd(xs):
    n = len(xs)
    m = sum(xs) / n
    v = sum((x - m) ** 2 for x in xs) / (n - 1) if n > 1 else float("nan")
    return m, math.sqrt(v)


def main(out):
    out = Path(out)
    if out.exists():
        raise SystemExit(f"{out} exists")
    runs, bad = load()
    lines = ["# E026 summary (generated by analyze.py)", ""]
    lines.append("N per arm: " + ", ".join(f"{a} {len(runs[a])}" for a in ARMS))
    if bad:
        lines.append(f"Runs not reaching the board or with errors (left out): {bad}")
    lines.append("")
    for name, fn in MEASURES:
        lines.append(f"## {name}")
        lines.append("")
        lines.append("| arm | N | mean | sd | diff to base (unpaired, 95%) | diff to base (paired by seed, 95%) |")
        lines.append("| --- | --- | --- | --- | --- | --- |")
        base = {s: fn(r) for s, r in runs["base"].items()}
        for a in ARMS:
            xs = {s: fn(r) for s, r in runs[a].items()}
            if len(xs) < 2:
                lines.append(f"| {a} | {len(xs)} | | | | |")
                continue
            m, sd = mean_sd(list(xs.values()))
            if a == "base" or len(base) < 2:
                lines.append(f"| {a} | {len(xs)} | {m:.3f} | {sd:.3f} | | |")
                continue
            mb, sdb = mean_sd(list(base.values()))
            se = math.sqrt(sd ** 2 / len(xs) + sdb ** 2 / len(base))
            d = m - mb
            common = sorted(set(xs) & set(base))
            if len(common) > 1:
                dm, dsd = mean_sd([xs[s] - base[s] for s in common])
                pe = f"{dm:+.3f} +/- {1.96 * dsd / math.sqrt(len(common)):.3f} (n={len(common)})"
            else:
                pe = ""
            lines.append(f"| {a} | {len(xs)} | {m:.3f} | {sd:.3f} | {d:+.3f} +/- {1.96 * se:.3f} | {pe} |")
        lines.append("")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main(sys.argv[1])
