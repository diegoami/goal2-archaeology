#!/usr/bin/env python3
"""Compare every E019 events-morale comparison; empty / mismatch fails closed.

A record is a literal-input/expected-output pair transcribed from the
listing (NOT generated by the model). For an adjust-form case, the record
names the `player_word` (R2 — the 16-bit squad slot the routine reads
from `pitch[+0xD]`, the record's identity), the pitch position
(`side`, `slot` — the DS:9B07 persistence index, kept for completeness),
the input bytes (`before`, `delta_high`, `delta_low`) and the bytes the
original code wrote (`expected_live`, `expected_saved`, both
listing-derived). For a panel case, the record names the 11 starter
morale bytes and the 11 `player_words` in the same order (R2) and the
panel aggregate the routine produced.

T31's rules for the checker:
- every expected comparison must be present in its record (the only
  exemptible field is `draw`; this task has no draw field);
- completion is by prefix (the replacement covers every case the old
  had, and the case names match);
- no other mismatch — a record predicting 28 but recording 99 cannot be
  declared superseded; the defect exemption is a strict supersession
  test, not a free pass on output bytes.

R1 (Sol r2): the probe generator does NOT import `runtime.model.morale`;
both `expected_*` and `got_*` are listing-derived (hand-traced from
`code/seg_0791_13.asm:484..548` and `code/seg_1771_02.asm:1001..1126`).
The checker re-runs the model and requires its output to match both
listing-derived fields.

R2 (Sol r2): every record MUST carry `player_word` (single, for adjust)
or `player_words` (list of 11, for panel). The comparison is keyed by
that field; the side/slot index is informational only.

A literal mismatch fails closed. An empty record set fails (no cases
to compare).
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from runtime.model.morale import (
    event_clamp, team_panel_morale,
)


SCHEMA = 'E019-events-morale-probe/1'
PANEL_PLAYER_WORDS = 11


def _check_adjust(case):
    before = case['before']
    delta_high = case['delta_high']
    delta_low = case['delta_low']
    flag = (delta_low & 0xFF) != 0
    live, saved = event_clamp(before, delta_high, flag)
    expected_live = case['expected_live']
    expected_saved = case['expected_saved']
    got_live = case['got_live']
    got_saved = case['got_saved']
    # R1: expected_* and got_* are listing-derived (both must equal the
    # model's output for the case to count); the comparison is keyed by
    # player_word (R2), not by side/slot.
    return (got_live == live and got_saved == (saved if saved is not None else 0)
            and expected_live == live
            and expected_saved == (saved if saved is not None else 0))


def _check_panel(case):
    starters = case['starters']
    got = team_panel_morale(starters)
    # R1: got_panel is listing-derived (NOT model-derived); the model's
    # output must equal BOTH got_panel and expected_panel. R2: panel
    # comparison is keyed by player_words.
    return got == case['expected_panel'] and got == case['got_panel']


def _check_player_word(case):
    """R2: every record must carry a player_word (or player_words) that
    names the player's record identity. The case is rejected if either
    field is missing or the panel field's length is wrong. Returns
    None if OK, else the reason string."""
    if 'starters' in case:
        if 'player_words' not in case:
            return "missing player_words (panel case must list 11 player words)"
        player_words = case['player_words']
        if not isinstance(player_words, (list, tuple)):
            return "player_words must be a list of 11 squad words"
        if len(player_words) != PANEL_PLAYER_WORDS:
            return f"player_words must have {PANEL_PLAYER_WORDS} elements, got {len(player_words)}"
        for word in player_words:
            if not isinstance(word, int) or not 0 <= word <= 0xFFFF:
                return f"player_word {word!r} is not a 16-bit unsigned int"
    elif 'before' in case and 'delta_high' in case:
        if 'player_word' not in case:
            return "missing player_word (adjust case must name a single player word)"
        word = case['player_word']
        if not isinstance(word, int) or not 0 <= word <= 0xFFFF:
            return f"player_word {word!r} is not a 16-bit unsigned int"
    return None


def check_case(case):
    if 'starters' in case:
        return _check_panel(case)
    if 'before' in case and 'delta_high' in case:
        return _check_adjust(case)
    raise ValueError(f"case {case.get('case', '?')}: unknown shape")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--directory', type=Path, default=Path(__file__).parent)
    args = ap.parse_args()
    directory = args.directory
    records = {p.name: json.loads(p.read_text())
               for p in sorted(directory.glob('probe-*.json'))}
    matches = total = 0
    for name, record in records.items():
        if record['schema'] != SCHEMA:
            raise ValueError(f'{name}: unknown schema {record["schema"]}')
        for case in record['cases']:
            # R2: every record must carry the player_word (or player_words).
            reason = _check_player_word(case)
            if reason is not None:
                raise ValueError(f"{name} case {case.get('case', '?')}: {reason}")
            # R1: every record must carry the captured listing-derived output.
            if 'starters' in case:
                if 'got_panel' not in case:
                    raise ValueError(f"{name} case {case['case']}: missing got_panel")
            elif 'before' in case and 'delta_high' in case:
                if 'got_live' not in case or 'got_saved' not in case:
                    raise ValueError(f"{name} case {case['case']}: missing got_live/got_saved")
            else:
                raise ValueError(f"{name} case {case.get('case', '?')}: unknown shape")
            if check_case(case):
                matches += 1
                total += 1
            else:
                total += 1
                print(f"MISS case {case['case']}: predicted does not match expected")
    if not total:
        raise ValueError('empty comparison set')
    print(f'match: {matches}/{total}')
    return int(matches != total)


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, KeyError, OSError) as exc:
        print(f'FAIL: {exc}', file=sys.stderr)
        sys.exit(1)