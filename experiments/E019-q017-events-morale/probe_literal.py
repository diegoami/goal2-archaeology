#!/usr/bin/env python3
"""Literal-input probe records for the E019 listing-derived arithmetic.

Each record is a literal-input/expected-output pair transcribed by hand
from the listing (NOT generated by the model, NOT a Unicorn emulation
of the original routine). The expected bytes for the adjust-form cases
come from a byte-for-byte trace of `0791:7CC5`
(`code/seg_0791_13.asm:484..548`) — push bp; mov bp, sp; sub sp, 4;
les di, [bp+6]; mov ax, es:[di+0xD]; mul 0x14; les di, [0xA91B]; add
di, ax; les di, [bp-4]; mov al, es:[di+0xC]; cwde; add ax, [bp+0xC];
clamp_int(0xFF, 1, &ax) via 214B:2000; mov al, [bp+0xC]; mov es:[di+0xC],
al; cmp byte [bp+0xA], 0; je skip; min_longint(32, s8(new)) via 214B:0D1C;
DS:9B07[side*20+slot] = al. The expected bytes for the team-panel cases
come from a byte-for-byte trace of `1771:13D0`
(`code/seg_1771_02.asm:1001..1126`) — DS:9B5A..9B64 := 6; per available
slot: DS:9B5A += min(32, s8(+0xC)); then `div cx` (cx=11, unsigned 16-bit
divide) and `cmp word ptr [0x9B5A], 1; jae`. For [128, 0, ..., 0] the
total is (6 + (-128)) & 0xFFFF = 0xFF86 = 65414; 65414 // 11 = 5946.
The reproduction of the routine bytes in Unicorn trips on a later library
call inside the engine (the readme documents this), so the expected bytes
are hand-derived; each record names the listing lines the derivation came
from.

The cases are identified by `player_word` (R2) — the 16-bit slot the
engine uses for the player's record, the value the routine reads from
`pitch[+0xD]` and indexes the squad by (`mov ax, word ptr es:[di + 0xd];
mul 0x14; les di, [0xa91b]; add di, ax`, `code/seg_0791_13.asm:487-495`).
The pitch position (side, slot) is the DS:9B07 index the persistence
write uses; it is independent of the player word. For panel cases, the
11 `player_words` are listed in the same order as the 11 starter morale
bytes — the routine walks slots 1..11 and reads
`pitch[A917 + 2*slot - 2]` for each available starter
(`code/seg_1771_02.asm:1018-1042`).

R1 (Sol r3): the adjust-case interface now takes LITERAL
`expected_live` and `expected_saved` per case (just as `panel_case`
already took `expected_panel`). The `got_*` values come from a
SEPARATE call to `_listing_event_clamp` below — they are NOT the same
expression as `expected_*`. This way, if the listing-derive function
in this module and the runtime model are both wrong in the same way,
the literal `expected_*` (hand-traced from the listing) still catches
the divergence. The probe generator does NOT import
`runtime.model.morale`; the model's output is verified independently
by the checker.

The records are the source of truth for the model's arithmetic; the
checker compares them against the model's output.
"""
import json
from pathlib import Path


# Listing-derived constants (hand-traced from the original code).
BYTE_BITS = 8
WORD_BITS = 16
LIVE_LOWER = 1
LIVE_UPPER = 255
SAVED_UPPER = 32
PANEL_MAX = 32
PANEL_SEED = 6
PANEL_DIVISOR = 11
PANEL_FLOOR = 1


def _signed(value, bits):
    value &= (1 << bits) - 1
    return value - (1 << bits) if value & (1 << (bits - 1)) else value


def _listing_event_clamp(before, delta, persist):
    """Listing arithmetic of 0791:7CC5 (hand-traced from
    code/seg_0791_13.asm:484..548). Independent of runtime.model.morale.

    live  = clamp_int(s8(before) + s16(delta), 1, 255)
    saved = min(32, s16(s8(live))) & 0xFF  if persist, else None
    """
    value = _signed(_signed(before, BYTE_BITS) + _signed(delta, WORD_BITS), WORD_BITS)
    live = min(LIVE_UPPER, max(LIVE_LOWER, value))
    if not persist:
        return live, None
    saved = min(SAVED_UPPER, _signed(live, BYTE_BITS)) & 0xFF
    return live, saved


def _listing_team_panel(morales):
    """Listing arithmetic of 1771:13D0 (hand-traced from
    code/seg_1771_02.asm:1001..1126). Independent of runtime.model.morale.

    total = 6
    for m in morales:
        total += min(32, s8(m))     # 16-bit add, wraps mod 0x10000
    quotient = total // 11          # unsigned 16-bit divide
    return max(1, quotient)         # the floor of 1 (line 1120)
    """
    total = PANEL_SEED
    for value in morales:
        signed = _signed(value, BYTE_BITS)
        contribution = min(PANEL_MAX, signed)
        total = (total + contribution) & 0xFFFF
    quotient = total // PANEL_DIVISOR
    return max(PANEL_FLOOR, quotient)


def _build_adjust_case(*, label, before, delta_high, delta_low, side, slot,
                       player_word, source, expected_live, expected_saved):
    """Build one 7CC5 case dict at runtime (R1 — Sol r3). The source
    string is the listing lines the expected bytes were derived from
    (e.g. 'seg_0791_13.asm:484..548'). `expected_live` and
    `expected_saved` are LITERAL ints — hand-traced from the listing
    (Unicorn capture of 0791:7CC5, or a byte-for-byte trace of
    `code/seg_0791_13.asm:484..548` / `seg_0791_06.c:595`), NOT
    computed from any function in this module. `got_live` and
    `got_saved` come from a SEPARATE call to `_listing_event_clamp()`
    below (resolved at call time, so a monkey-patch of
    `_listing_event_clamp` before `main()` affects the got_* values),
    which is the module's hand-traced arithmetic and is independent of
    `runtime.model.morale`. The checker verifies the model's output
    equals BOTH.

    If the listing-derive and the runtime model are both wrong in the
    same way, the literal `expected_*` (independent of both) still
    catches the divergence: the model output diverges from
    `expected_*`.

    `player_word` is the 16-bit slot the routine reads from
    `pitch[+0xD]` (R2) — the player's record identity, NOT the side/slot
    position. `side` and `slot` are the DS:9B07 persistence index.
    """
    got_live, got_saved = _listing_event_clamp(before, delta_high, (delta_low & 0xFF) != 0)
    got_saved_value = got_saved if got_saved is not None else 0
    return {
        'case': label,
        'method': 'literal listing arithmetic; 0791:7CC5 with named delta',
        'source': source,
        'player_word': player_word,
        'side': side,
        'slot': slot,
        'before': before, 'delta_high': delta_high, 'delta_low': delta_low,
        # R1 (Sol r3): expected_* are LITERAL ints; got_* come from a
        # separate call to _listing_event_clamp (NOT the same expression).
        'expected_live': expected_live, 'expected_saved': expected_saved,
        'got_live': got_live, 'got_saved': got_saved_value,
    }


def _build_panel_case(label, starters, player_words, expected_panel, source):
    """Build one literal 1771:13D0 case. expected_panel is hand-derived
    from the listing (NOT from the model); got_panel comes from a
    SEPARATE call to `_listing_team_panel` (resolved at call time so a
    monkey-patch before `main()` affects the got value), which is
    independent of `runtime.model.morale`. `player_words` is a list of
    11 squad words in the same order as the 11 starter morale bytes
    (R2) — the routine walks slots 1..11 and reads
    `pitch[A917 + 2*slot - 2]` for each available starter.
    """
    got = _listing_team_panel(starters)
    return {
        'case': label,
        'method': 'literal listing arithmetic; 1771:13D0 over available starters',
        'source': source,
        'player_words': list(player_words),
        'starters': list(starters),
        'expected_panel': expected_panel,
        'got_panel': got,
    }


