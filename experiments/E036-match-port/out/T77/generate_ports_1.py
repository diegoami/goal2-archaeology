mapping=[]
for module in ('quick','rare'):
 entries=rs[:3]+rs[-1:] if module=='quick' else rs[3:-1]
 source=HEADER+f'PORTS=Registry({module!r},"T77 '+('quick result and team line strengths' if module=='quick' else 'rare match branches')+'")\n'
 if module=='quick':
  source+='PORTS.variant("trial-no-goal","B261 omits one successful trial goal")\nPORTS.variant("energy-no-decay","DAC1 omits the signed-energy decrement")\nPORTS.variant("stats-no-shot","D805 omits the shot statistic increment")\n'
  source+=HELPERS
 else: source+='from .quick import _read, _write, _pop, _call\n\n'
 for target in entries:
  seg,entry=target.split(':');ins=routines[target];SEGMENT=int(seg,16)
  skip=set();calls={}
  for i,(pc,op,arg) in enumerate(ins):
   if op!='call':continue
   far=arg.startswith('far ')
   dst=arg[4:] if far else f'{seg}:{int(arg,0)&65535:04X}'
   rop,rarg=ret(dst);n=int(rarg,0)//2 if rarg else 0
   if not far and i and ins[i-1][1:]==('push','cs'):
    skip.add(ins[i-1][0]);far=True
   assert far==(rop=='retf'),(target,hex(pc),dst,far,rop)
   calls[pc]=(dst,n,ins[i+1][0],far)
  leaders={ins[0][0]}
  for i,(pc,op,arg) in enumerate(ins):
   if op.startswith('j'):
    leaders.add(int(arg,0)&65535)
    if i+1<len(ins):leaders.add(ins[i+1][0])
  blocks=[]
  for inst in ins:
   if inst[0] in leaders:blocks.append([])
   blocks[-1].append(inst)
  rop,rarg=ret(target);rtext=rop+(' '+rarg if rarg else '')
  source+=f'\n\n@PORTS.port({target!r},ret={rtext!r})\ndef listing_{seg}_{entry}(mem,variant):\n    r=Regs(mem)\n    pc=0x{entry}\n    z=False; unsigned=0; signed=0\n    while True:\n'
  for bi,block in enumerate(blocks):
   source+=f'        {"if" if bi==0 else "elif"} pc == 0x{block[0][0]:04X}:\n'
   emitted=0;terminal=False
   for pc,op,arg in block:
    if pc in skip:continue
    at=f'{seg}:{pc:04X}';out=[];parts=arg.split(', ')
    if op in ('ret','retf'):
     out=['r.store(stack=True)','return None'];terminal=True
    elif op=='mov':out=[write(parts[0],read(parts[1]),at)]
    elif op=='lea':out=[write(parts[0],offset(parts[1]),at)]
    elif op=='les':
     a,b=address(parts[1]);out=[f'_off={b}',f'_seg={a}',f'r.di=_read(mem,r,_seg,_off,16)',f'r.es=_read(mem,r,_seg,_off+2,16)']
    elif op=='push':out=[f'r.push({read(arg).replace("SEGMENT",str(SEGMENT))})']
    elif op=='pop':out=[write(arg,'_pop(mem,r)',at)]
    elif op=='cmp':out=[f'_a={read(parts[0])}; _b={read(parts[1])}',f'z=_a==_b; unsigned=_a-_b; signed=((_a ^ {1<<(width(parts[0])-1)})-(_b ^ {1<<(width(parts[0])-1)}))']
    elif op in ('add','sub','xor','or','shl','inc','dec'):
     dst=parts[0];a=read(dst);b=read(parts[1]) if len(parts)>1 else '1';symbol={'add':'+','sub':'-','xor':'^','or':'|','shl':'<<','inc':'+','dec':'-'}[op]
     out=[f'_v=({a} {symbol} {b}) & {(1<<width(dst))-1}',write(dst,'_v',at),'z=_v==0']
     # T77's branch falsifiers are actual memory changes at their listing sites.
     if module=='quick' and pc in (0xB261,0xDAC1,0xD805):
      vn={0xB261:'trial-no-goal',0xDAC1:'energy-no-decay',0xD805:'stats-no-shot'}[pc]
      out=[f'if variant != {vn!r}:']+['    '+s for s in out]
    elif op=='cwde':out=['r.ax=((r.ax & 255)^128)-128']
    elif op=='cdq':out=['r.dx=65535 if r.ax & 32768 else 0']
    elif op in ('mul','imul'):
     a='r.ax' if op=='mul' else 's16(r.ax)';b=read(arg) if op=='mul' else f's16({read(arg)})'
     out=[f'_v={a}*{b}','r.ax=_v','r.dx=_v >> 16']
    elif op in ('div','idiv'):
     out=['_v=(r.dx << 16)|r.ax',f'_divisor={read(arg)}']
     if op=='idiv':out+=['_v=(_v ^ 2147483648)-2147483648','_divisor=s16(_divisor)','_q=abs(_v)//abs(_divisor)','_q=-_q if (_v<0)!=(_divisor<0) else _q','r.ax=_q','r.dx=_v-_q*_divisor']
     else:out+=['r.ax,r.dx=divmod(_v,_divisor)']
    elif op=='xchg':out=[f'_v={read(parts[0])}',write(parts[0],read(parts[1]),at),write(parts[1],'_v',at)]
    elif op=='call':
     dst,n,after,far=calls[pc];out=[f'r=yield from _call(mem,r,{dst!r},{n},{seg+":"+format(after,"04X")!r},{far!r})','z=bool(mem.reg("eflags") & 64)']
    elif op.startswith('j'):
     dest=int(arg,0)&65535
     cond={'je':'z','jne':'not z','ja':'unsigned>0','jae':'unsigned>=0','jb':'unsigned<0','jbe':'unsigned<=0','jle':'signed<=0'}.get(op)
     if op=='jmp':out=[f'pc=0x{dest:04X}','continue']
     else:
      idx=next(i for i,x in enumerate(ins) if x[0]==pc);out=[f'pc=0x{dest:04X} if {cond} else 0x{ins[idx+1][0]:04X}','continue']
     terminal=True
    else:raise ValueError((target,pc,op,arg))
    source+=f'            # {pc:04X} {op} {arg}\n'+''.join('            '+x+'\n' for x in out);emitted+=1
    mapping.append({'entry':target,'pc':at,'operation':op+' '+arg})
   if not terminal:
    source+=f'            pc=0x{blocks[bi+1][0][0]:04X}\n            continue\n' if bi+1<len(blocks) else '            raise AssertionError("fell past listing")\n'
   if not emitted:source+='            pass\n'
  source+='        else:\n            raise AssertionError(pc)\n'
