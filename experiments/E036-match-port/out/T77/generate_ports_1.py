 if '[' in x:
  seg,off=address(x);return f'_read(mem,r,{seg},{off},{width(x)})'
 if x in REGS:return 'r.'+x
 if x in HALVES:
  reg,shift=HALVES[x];return f'((r.{reg} >> {shift}) & 255)'
 if x=='ds':return 'mem.DS'
 if x=='ss':return 'r.ss'
 if x=='cs':return 'mem.seg(SEGMENT)'
