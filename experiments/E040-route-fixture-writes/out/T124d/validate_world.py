HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[3]
sys.path[:0]=[str(ROOT),str(ROOT/'runtime'),str(HERE)]
import prepare as P
_spec=importlib.util.spec_from_file_location('_validation_original_reference',HERE/'reference.py')
REF=importlib.util.module_from_spec(_spec);_spec.loader.exec_module(REF)


def check(entry,after,label):
    r=P.load(entry);m=r.m;before=P.aggregate_records(m)
    REF.original_call(r,'1771:85F7','1771:883B',0x3E00,0x3E80,far=False)
    assert P.aggregate_records(m)==before,'stored aggregates were not finalized original85F7 outputs'
    winners=[]
    for i,v in enumerate(before):
        a=v['aggregate'];first,second=v['legs']
        assert (first['side4'],first['side6'])==(second['side6'],second['side4'])==(a['side4'],a['side6'])
        assert a['score_or_mark']==(first['score_or_mark']+second['second_score_or_group'])&255
        assert a['second_score_or_group']==(first['second_score_or_group']+second['score_or_mark'])&255
        assert a['score_or_mark']<254 and a['second_score_or_group']<254 and a['winner_flag'] in (0,1)
        off=(m.rd(0xA92B)+8*(2400+i))&65535;seg=m.rd(0xA92D)
        REF.original_call(r,'1771:5C94','1771:72CD',0x3E00,0x3E80,(seg,off),far=True)
        winner=m.reg('ax');assert winner==(a['side6'] if a['winner_flag']==1 else a['side4'])
        winners.append(winner)
    out={'label':label,'group_entry_sha256':entry['sha256'],'original85F7_idempotent':True,
         'aggregate_leg_relationships':True,'actual_original5C94_winners':winners,'aggregates':before}
    if after:
        b=P.load(after).m;table=b.far(0xA933);allteams=[]
        for g in range(1,9):
            actual={b.word_at(table+g*0x38+0x14C8+8*i) for i in range(4)}
            expected={b.word_at(table+g*0x38+0xDC8),b.word_at(table+(9-g)*0x38+0xDD0),
                      b.word_at(table+g*0x38+0xF88),winners[g-1]}
            assert actual==expected;allteams.extend(actual)
        assert len(set(allteams))==32
        out.update(groups_entry_membership_valid=True,unique_finalists=32)
    return out


