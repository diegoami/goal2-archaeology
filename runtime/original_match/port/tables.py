"""T80: the loader of the original's constant tables, from a folder the caller gives (no byte of the original here).

[designed: owner, 2026-10-29, T80a] The sealed engine reads GOAL.EXE's constant data from two tables, never from
GOAL.EXE at run time: the initialised data segment DS:0000..7B6F and the code segments' data areas the static
listing reports (static/goal-exe/tables/manifest.json, generated by tools/static/port_tables.py, which also builds
them from the player's own GOAL.EXE; goal2 never ships them). The folder holds manifest.json, ds.hex and
code_data.hex. `load(folder)` reads them and refuses tables whose digests are not the manifest's; `place` writes
them into a guest memory at a load segment's positions. [derived: experiments/E036-match-port/out/T80/b/inputs-v1.md,
probe v5: every admitted match equals the original from these tables plus the game's state, 75 of 75]
"""
import hashlib
import json
from pathlib import Path

DS_PARAGRAPH = 0x2581       # the data segment, in paragraphs from the load segment (static/goal-exe/README.md)
DS_INIT = 0x7B70            # the initialised part of the data segment: DS:0000..7B6F
MODULE_SIZE = DS_PARAGRAPH * 16 + DS_INIT    # GOAL.EXE's load module in memory: its code, then its initialised data


class TablesError(ValueError):
    pass


def from_hex(text):
    """The bytes of a table in static/goal-exe/data's hex format (tools/static/port_tables.py to_hex)."""
    out, previous = bytearray(), None
    rows = [l for l in text.splitlines() if l and not l.startswith(";")]
    base = int(rows[0].split()[0], 16) if rows else 0
    for i, line in enumerate(rows):
        if line.strip() == "*":
            nxt = int(rows[i + 1].split()[0], 16) - base
            while len(out) < nxt:
                out += previous
            continue
        head = line.split("|")[0].split()
        if len(head) == 1:
            break                                   # the final offset: the table's length
        previous = bytes(int(x, 16) for x in head[1:])
        out += previous
    return bytes(out)


class Tables:
    """GOAL.EXE's constant tables: `ds` (DS:0000..7B6F) and `code_data` [(offset from the load segment, bytes)]."""

    def __init__(self, ds, code_data, sha256):
        self.ds, self.code_data, self.sha256 = ds, code_data, sha256

    def place(self, memory, load):
        """Write both tables into `memory` (a bytearray of guest memory) for a program loaded at paragraph `load`."""
        base = load * 16
        ds = base + DS_PARAGRAPH * 16
        memory[ds:ds + len(self.ds)] = self.ds
        for off, raw in self.code_data:
            memory[base + off:base + off + len(raw)] = raw


def load(folder):
    folder = Path(folder)
    try:
        manifest = json.loads((folder / "manifest.json").read_text())
        ds = from_hex((folder / "ds.hex").read_text())
        code = from_hex((folder / "code_data.hex").read_text())
    except (OSError, ValueError) as e:
        raise TablesError(f"no readable tables in {folder}: {e}") from None
    want = manifest.get("sha256") or {}
    if hashlib.sha256(ds).hexdigest() != want.get("ds") or hashlib.sha256(code).hexdigest() != want.get("code_data"):
        raise TablesError(f"the tables in {folder} differ from their manifest's digests")
    if manifest["ds"]["length"] != DS_INIT or len(ds) != DS_INIT:
        raise TablesError("the data table is not DS:0000..7B6F")
    areas, at = [], 0
    for off, n in manifest["code_data"]:
        areas.append((off, code[at:at + n]));at += n
    if at != len(code):
        raise TablesError("the code-data table's length differs from its manifest")
    return Tables(ds, areas, dict(want))
