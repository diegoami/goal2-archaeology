#!/usr/bin/env python3
"""T80a: the plain port's constant tables, from a GOAL.EXE, and their check.

    python3 -B tools/static/port_tables.py manifest            # (re)derive static/goal-exe/tables/manifest.json
    python3 -B tools/static/port_tables.py extract --exe GOAL.EXE --out DIR   # the tables from a GOAL.EXE
    python3 -B tools/static/port_tables.py --check             # the committed tables against everything below

[designed: owner, 2026-10-29, T80a] The sealed engine reads the original's constant data from tables,
never from GOAL.EXE at run time. They are two areas of the unpacked image:
- the initialised data segment, DS:0000..7B6F (image 25810..2D37F), all of it: the port reads 4,396
  bytes outside build.py's measured ranges (experiments/E036-match-port/out/T80/a/read-map-family-v1.json),
  so a measured subset is not enough; bytes the game writes before a match come from its state (T80b);
- every byte the static listing reports as data inside the code segments (static/goal-exe/code/*.asm,
  "; data (not reached as code), N bytes": 173 areas, 11,572 bytes), the tables the port reads there.
The manifest holds positions and digests only. `extract` slices any GOAL.EXE (packed LZEXE 0.91 or
unpacked) at the manifest's positions and refuses one whose slices do not match the manifest's
digests: it is how goal2 builds the tables from the player's own file (it never ships them).
`--check` verifies: the manifest re-derives from the listing; the committed tables equal `extract` of
the registered GOAL.EXE (when it is in .cache/artifacts); the data part equals static/goal-exe/data;
build.py's data digests hold on it; and every byte the port read in the family read map lies inside
the tables, except the bytes named there as state.
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / "tools/static"), str(ROOT / "runtime")]
TABLES = ROOT / "static/goal-exe/tables"
MANIFEST = TABLES / "manifest.json"
LISTING = ROOT / "static/goal-exe/code"
DATA_HEX = ROOT / "static/goal-exe/data"
READ_MAP = ROOT / "experiments/E036-match-port/out/T80/a/read-map-family-v1.json"
REGISTERED = ROOT / ".cache/artifacts/goal2-a949da2f/GOAL.EXE"
DS_IMAGE, DS_INIT = 0x25810, 0x7B70
STATE_BYTES = {0x7968: "DS:7968, set by the game before a match (read map: differs from GOAL.EXE)"}
BLOCK = re.compile(r"^; data \(not reached as code\), (\d+) bytes\n([0-9A-F]{4}) ", re.M)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def to_hex(data, title):
    """static/goal-exe/data's format: 32 bytes a row, an ASCII column, '*' for a row repeating the one above."""
    lines = [f"; {title}", "; generated by tools/static/port_tables.py from the registered GOAL.EXE; not edited by hand",
             "; 32 bytes a row; '*' repeats the row above; offsets are positions in this table"]
    previous = None
    for at in range(0, len(data), 32):
        row = data[at:at + 32]
        if row == previous and len(row) == 32:
            if lines[-1] != "*": lines.append("*")
            continue
        previous = row
        text = "".join(chr(b) if 32 <= b < 127 else "." for b in row)
        lines.append(f"{at:05X}  {' '.join(f'{b:02X}' for b in row):<95}  |{text}")
    lines.append(f"{len(data):05X}")
    return "\n".join(lines) + "\n"


def from_hex(text):
    """The bytes of a table in that format (static/goal-exe/data's too)."""
    out, previous = bytearray(), None
    rows = [l for l in text.splitlines() if l and not l.startswith(";")]
    base = int(rows[0].split()[0], 16) if rows else 0     # a part of a split file starts where the last one ended
    for i, line in enumerate(rows):
        if line.strip() == "*":
            nxt = int(rows[i + 1].split()[0], 16) - base
            while len(out) < nxt:
                out += previous
            continue
        head = line.split("|")[0].split()
        if len(head) == 1:
            break                                   # the final offset: the table's length
        previous = bytes(int(x, 16) for x in head[1:])
        out += previous
    return bytes(out)


def code_areas():
    """[(image offset, length)] of the listing's data areas in the code segments."""
    areas = []
    for path in sorted(LISTING.glob("seg_*.asm")):
        segment = int(path.name.split("_")[1], 16)
        for n, off in BLOCK.findall(path.read_text()):
            areas.append((segment * 16 + int(off, 16), int(n)))
    return sorted(areas)


def image_of(exe):
    """The load module of a GOAL.EXE (unpacked first when it is LZEXE-packed)."""
    import unlzexe
    data = exe if exe[0x1C:0x20] != b"LZ91" else unlzexe.unpack(exe)
    return data[int.from_bytes(data[8:10], "little") * 16:]


def derive_manifest():
    areas = code_areas()
    return {"schema": 1, "source": "static/goal-exe/code listing (data areas) and DS:0000..7B6F",
            "ds": {"image_offset": DS_IMAGE, "length": DS_INIT},
            "code_data": [[o, n] for o, n in areas], "state_bytes": {f"{k:#06x}": v for k, v in STATE_BYTES.items()}}


def slices(image, manifest):
    ds = image[manifest["ds"]["image_offset"]:manifest["ds"]["image_offset"] + manifest["ds"]["length"]]
    code = b"".join(image[o:o + n] for o, n in manifest["code_data"])
    return ds, code


def extract(exe_path, out_dir, manifest=None):
    manifest = manifest or json.loads(MANIFEST.read_text())
    ds, code = slices(image_of(Path(exe_path).read_bytes()), manifest)
    want = manifest.get("sha256")
    if want and (sha(ds) != want["ds"] or sha(code) != want["code_data"]):
        raise SystemExit("this GOAL.EXE is not the registered one: its tables differ from the manifest's digests")
    out = Path(out_dir);out.mkdir(parents=True, exist_ok=True)
    write_tables(out, ds, code)
    return ds, code


def write_tables(out, ds, code):
    (out / "ds.hex").write_text(to_hex(ds, "GOAL.EXE's initialised data segment, DS:0000..7B6F (T80a)"))
    (out / "code_data.hex").write_text(to_hex(code, "GOAL.EXE's data areas in the code segments, in the manifest's order (T80a)"))


def read_tables(folder):
    return from_hex((folder / "ds.hex").read_text()), from_hex((folder / "code_data.hex").read_text())


def check():
    problems = []
    manifest = json.loads(MANIFEST.read_text())
    derived = derive_manifest()
    if {k: v for k, v in manifest.items() if k != "sha256"} != derived:
        problems.append("the manifest does not re-derive from the listing")
    ds_hex = b"".join(from_hex(p.read_text()) for p in sorted(DATA_HEX.glob("ds_2581_*.hex")))
    present = (TABLES / "ds.hex").exists() and (TABLES / "code_data.hex").exists()
    ds, code = read_tables(TABLES) if present else (None, None)
    if not present:
        problems.append("static/goal-exe/tables/ds.hex or code_data.hex is missing")
    else:
        if sha(ds) != manifest["sha256"]["ds"] or sha(code) != manifest["sha256"]["code_data"]:
            problems.append("the committed tables differ from the manifest's digests")
        if ds != ds_hex[:len(ds)] or len(ds_hex) < len(ds):
            problems.append("the data table differs from static/goal-exe/data")
        from original_match import build
        for block, digest in build.DATA_SHA256.items():
            lo, hi = block * build.DATA_BLOCK, (block + 1) * build.DATA_BLOCK
            measured = b"".join(ds[o:o + n] for o, n in build.DATA_RANGES if lo <= o < hi)
            if sha(measured) != digest:
                problems.append(f"build.py's data digest of block {block} does not hold on the table")
        if sum(n for _, n in manifest["code_data"]) != len(code):
            problems.append("the code-data table's length differs from the manifest")
        if REGISTERED.exists():
            fresh_ds, fresh_code = slices(image_of(REGISTERED.read_bytes()), manifest)
            if fresh_ds != ds or fresh_code != code:
                problems.append("the committed tables differ from the registered GOAL.EXE's")
    if READ_MAP.exists():
        rmap = json.loads(READ_MAP.read_text())
        covered = {o + i for o, n in manifest["code_data"] for i in range(n)}
        for o, n in rmap["regions"]["code"]["table_ranges"]:
            missing = [x for x in range(o, o + n) if x not in covered]
            if missing:
                problems.append(f"the port read code bytes outside the tables at image {missing[0]:#x} ({len(missing)} bytes)")
        for hexoff, n in rmap["regions"]["initialised data"]["differ_ranges"]:
            if int(hexoff, 16) not in STATE_BYTES:
                problems.append(f"DS:{hexoff} differs from GOAL.EXE in the read map and is not named as state")
    for p in problems:
        print("FAIL:", p)
    print("port tables check:", "FAIL" if problems else "ok")
    return 1 if problems else 0


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    sub = ap.add_subparsers(dest="cmd")
    sub.add_parser("manifest")
    e = sub.add_parser("extract");e.add_argument("--exe", required=True);e.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    if a.check:
        return check()
    if a.cmd == "manifest":
        manifest = derive_manifest()
        ds, code = slices(image_of(REGISTERED.read_bytes()), manifest)
        manifest["sha256"] = {"ds": sha(ds), "code_data": sha(code)}
        TABLES.mkdir(parents=True, exist_ok=True)
        MANIFEST.write_text(json.dumps(manifest, indent=1) + "\n")
        write_tables(TABLES, ds, code)
        assert read_tables(TABLES) == (ds, code), "the hex tables do not read back"
        print(f"manifest: {len(manifest['code_data'])} code-data areas ({len(code)} bytes), DS {len(ds)} bytes")
        return 0
    if a.cmd == "extract":
        ds, code = extract(a.exe, a.out)
        print(f"tables written to {a.out}: ds {len(ds)} bytes, code_data {len(code)} bytes")
        return 0
    ap.print_help();return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
