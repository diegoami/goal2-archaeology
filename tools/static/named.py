#!/usr/bin/env python3
"""Write static/goal-exe/named/, the named view of the decompiled GOAL.EXE (T20).

Called by `tools/static/decompile.sh --annotations <dir> ...`; not normally run by hand. Its input
is the raw output of tools/static/ghidra/GoalDecompile.java run after GoalAnnotate.java applied the
annotations (routine names, the record structures typed on the array pointers, global names and
types). It lays the files out as tools/static/decompiled.py does for decompiled/ (per-segment files
under the size limit, index.tsv, README.md) and rewrites addresses the same way. The differences:
  - a function's listing address comes from its Ghidra address, since an annotated function carries
    its name instead of f_SSSS_OOOO;
  - each heading keeps the listing address and the raw name, and adds the annotation's purpose,
    confidence and basis;
  - a call Ghidra left unresolved (func_SSSS_OOOO after the rewrite) to an annotated routine gets
    the routine's name;
  - index.tsv gains the name and confidence; README.md the coverage per segment.
The output depends only on its inputs.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import decompiled as raw  # noqa: E402  tools/static/decompiled.py

RTL_SEGMENTS = ("214B", "2138", "2139", "235C", "2382", "23E4")  # check_annotations.py


def read_tsv(path: Path) -> list[dict[str, str]]:
    lines = [l for l in path.read_text(encoding="utf-8").split("\n") if l.strip() and not l.startswith(";")]
    header = lines[0].split("\t")
    return [dict(zip(header, l.split("\t"))) for l in lines[1:]]


def listing_of(f: raw.Function, segmap: raw.SegMap) -> str:
    gseg, off = (int(x, 16) for x in f.ghidra.split(":"))
    return f"{segmap.to_listing[gseg]:04X}:{off:04X}"


def render(functions: list[raw.Function], routines: list[str], segmap: raw.SegMap,
           names: dict[str, dict[str, str]]) -> tuple[dict[str, str], list[list[str]]]:
    """The .c files (name -> text) and the rows of index.tsv."""
    known = set(routines)
    by_listing = {listing_of(f, segmap): f for f in functions}
    call_names = {"func_" + a.replace(":", "_"): r["name"] for a, r in names.items()}
    files: dict[str, list[str]] = {}
    where: dict[str, tuple[str, int]] = {}
    current: dict[int, tuple[str | None, int]] = {}
    for addr in sorted(by_listing):
        f = by_listing[addr]
        if not f.ok:
            continue
        seg = int(addr.split(":")[0], 16)
        found = "routines.tsv" if addr in known else "Ghidra's analysis (not in routines.tsv)"
        rawname = "f_" + addr.replace(":", "_")
        note = ""
        if addr in names:
            r = names[addr]
            note = f"// {r['purpose']}  [{r['confidence']}; {r['basis']}]\n"
        code = raw.rewrite(f.code, segmap)
        code = re.sub(r"\bfunc_[0-9A-F]{4}_[0-9A-F]{4}\b", lambda m: call_names.get(m.group(0), m.group(0)), code)
        block = (f"// ---- {addr}  {f.name}  ({rawname}; Ghidra {f.ghidra.upper()}, {f.convention}; "
                 f"found by {found})\n" + note + "\n" + code.strip("\n") + "\n\n\n")
        name, part = current.get(seg, (None, 0))
        if name is None or (len("".join(files[name]).encode()) + len(block.encode()) > raw.MAX_FILE_BYTES
                            and len(files[name]) > 1):
            part += 1
            name = f"seg_{seg:04X}_{part:02d}.c"
            current[seg] = (name, part)
            files[name] = [file_header(seg, part, segmap)]
        line = "".join(files[name]).count("\n") + 1
        files[name].append(block)
        where[addr] = (name, line)
    rows = []
    for addr in sorted(set(routines) | set(by_listing)):
        f = by_listing.get(addr)
        source = "routines.tsv" if addr in known else "ghidra"
        a = names.get(addr, {})
        ann = [a.get("name", ""), a.get("confidence", "")]
        if f is None:
            rows.append([addr] + ann + ["missing", "", "", "", source, "Ghidra made no function here"])
        elif f.ok:
            name, line = where[addr]
            rows.append([addr] + ann + ["decompiled", name, str(line), f.ghidra.upper(), source, ""])
        else:
            rows.append([addr] + ann + ["failed", "", "", f.ghidra.upper(), source, f.error])
    return {n: "".join(parts).rstrip("\n") + "\n" for n, parts in files.items()}, rows


def file_header(seg: int, part: int, segmap: raw.SegMap) -> str:
    table = ", ".join(f"{s:04X}={g:04X}" for s, g in sorted(segmap.to_ghidra.items()))
    return (f"// GOAL.EXE code segment {seg:04X}, part {part}: the named view, Ghidra's decompiler output "
            f"with the annotations of ../annotations/ applied, generated by tools/static/decompile.sh "
            f"--annotations (see README.md here; never edited by hand). Names are claims: each heading "
            f"gives the routine's confidence and basis; ../decompiled/ is the raw view of the same code.\n"
            f"// Headings give listing addresses (SEGMENT:OFFSET, as in ../code/). DS:XXXX is the "
            f"data segment 2581. A segment number written in the code (a far pointer's segment, a far "
            f"call's) is Ghidra's: listing=Ghidra {table}.\n\n")


def readme(files: dict[str, str], rows: list[list[str]], summary: str, ghidra: str, jdk: str,
           annotations: Path) -> str:
    segs: dict[str, list[int]] = {}
    for r in rows:
        if r[7] != "routines.tsv":
            continue
        c = segs.setdefault(r[0][:4], [0, 0])
        c[1] += 1
        c[0] += bool(r[1])
    lines = [
        "# static/goal-exe/named/",
        "",
        "The named view: the decompiled `GOAL.EXE` of `../decompiled/` with the annotations of "
        "`../annotations/` applied: routine names, the `player` and `country` records typed on the "
        "array pointers, global names and types. Generated, never edited by hand:",
        "",
        "```sh",
        "bash tools/static/decompile.sh --annotations static/goal-exe/annotations <released GOAL.EXE> static/goal-exe/named",
        "```",
        "",
        "rewrites every file here byte for byte (the same Ghidra run as `../decompiled/`, with "
        "`tools/static/ghidra/GoalAnnotate.java` before `GoalDecompile.java` and "
        "`tools/static/named.py` as the writer; `tools/static/check_annotations.py` must pass first). "
        f"Ghidra {ghidra}, JDK {jdk}.",
        "",
        "- Names are claims. Each annotated heading gives a second line: the purpose, the confidence "
        "(`established` for a finding's claim, `likely`, `guess`) and the basis (a finding, or the "
        "lines read). A routine nobody has read keeps its `f_SSSS_OOOO` name.",
        "- Each heading keeps the listing address and the raw name `f_SSSS_OOOO`, so a line here maps "
        "to `../decompiled/` and `../code/`. Addresses read as in `../decompiled/README.md`.",
        "- `../decompiled/` stays the raw baseline (F009). Where the two differ on what the code does, "
        "the listing decides: struct typing on far pointers is a trust limit of F009.",
        "- To add or correct a name: edit `../annotations/`, run the checker, regenerate this "
        "directory (`docs/process.md`, \"The named view\").",
        "",
        "## Coverage",
        "",
        "| segment | named | routines |",
        "| --- | --- | --- |",
    ]
    for seg in sorted(segs):
        tag = " (run-time library)" if seg in RTL_SEGMENTS else ""
        lines.append(f"| {seg}{tag} | {segs[seg][0]} | {segs[seg][1]} |")
    lines += ["", "- The scripts' own report: " + "; ".join(summary.strip().splitlines()) + ".", ""]
    lines += ["| File | What |", "| --- | --- |",
              "| `index.tsv` | per function: listing address, annotated name and confidence (the basis is "
              "in the heading and in `../annotations/routines.tsv`), "
              "decompiled or not, file and line of its heading, Ghidra address, found in `routines.tsv` "
              "or by Ghidra, why it failed |"]
    for name in sorted(files):
        lines.append(f"| `{name}` | code segment {name[4:8]}, part {int(name[9:11])} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--annotations", type=Path, required=True)
    ap.add_argument("--raw", type=Path, required=True)
    ap.add_argument("--segmap", type=Path, required=True)
    ap.add_argument("--summary", type=Path, required=True)
    ap.add_argument("--routines", type=Path, required=True)
    ap.add_argument("--ghidra", required=True)
    ap.add_argument("--jdk", required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    segmap = raw.SegMap.read(a.segmap)
    functions = raw.parse_raw(a.raw.read_text(encoding="utf-8"))
    names = {r["address"]: r for r in read_tsv(a.annotations / "routines.tsv")}
    files, rows = render(functions, raw.read_routines(a.routines), segmap, names)
    a.out.mkdir(parents=True, exist_ok=True)
    for old in list(a.out.glob("seg_*.c")) + [a.out / "index.tsv", a.out / "README.md"]:
        old.unlink(missing_ok=True)
    for name, text in files.items():
        (a.out / name).write_text(text, encoding="utf-8")
    index = ["address\tname\tconfidence\tstatus\tfile\tline\tghidra_address\tfound_in\tnote"]
    index += ["\t".join(r) for r in rows]
    (a.out / "index.tsv").write_text("\n".join(index) + "\n", encoding="utf-8")
    (a.out / "README.md").write_text(
        readme(files, rows, a.summary.read_text(encoding="utf-8"), a.ghidra, a.jdk, a.annotations),
        encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
